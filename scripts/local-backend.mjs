import { existsSync, mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { spawnSync } from "node:child_process";
const run = (cmd, args, options = {}) => {
  const r = spawnSync(cmd, args, { stdio: "inherit", ...options });
  if (r.status !== 0) throw Error(cmd + " failed.");
};
mkdirSync(".local", { recursive: true, mode: 0o700 });
if (!existsSync(".env.local")) {
  const admin = randomBytes(32).toString("hex"),
    app = randomBytes(32).toString("hex");
  writeFileSync(
    ".env.local",
    `DATABASE_URL=postgresql://farmos_app:${app}@127.0.0.1:55432/farmos\nFARMOS_WEB_ORIGIN=http://127.0.0.1:5173\n`,
    { mode: 0o600, flag: "wx" },
  );
  writeFileSync(
    ".local/admin.env",
    `MIGRATION_DATABASE_URL=postgresql://postgres:${admin}@127.0.0.1:55432/farmos\nFARMOS_DB_APP_PASSWORD=${app}\n`,
    { mode: 0o600, flag: "wx" },
  );
  writeFileSync(
    ".local/postgres.env",
    `POSTGRES_DB=farmos\nPOSTGRES_PASSWORD=${admin}\n`,
    { mode: 0o600, flag: "wx" },
  );
}
// Upgrade only the bootstrap file layout generated by earlier development builds.
if (!existsSync(".local/admin.env") && existsSync(".local/postgres.env")) {
  const lines = readFileSync(".env.local", "utf8").split("\n");
  const adminLines = lines.filter(
    (l) =>
      l.startsWith("MIGRATION_DATABASE_URL=") ||
      l.startsWith("FARMOS_DB_APP_PASSWORD="),
  );
  if (adminLines.length === 2) {
    writeFileSync(".local/admin.env", adminLines.join("\n") + "\n", {
      mode: 0o600,
      flag: "wx",
    });
    writeFileSync(
      ".env.local",
      lines.filter((l) => !adminLines.includes(l)).join("\n"),
      { mode: 0o600 },
    );
  }
}
if (!existsSync(".local/postgres.env"))
  throw Error(
    "Existing environment configuration found without local database bootstrap file; preserve it and configure the database manually.",
  );
const existing =
  spawnSync("docker", ["container", "inspect", "waterturn-farmos-db"], {
    stdio: "ignore",
  }).status === 0;
if (existing) run("docker", ["start", "waterturn-farmos-db"]);
else
  run("docker", [
    "run",
    "--detach",
    "--name",
    "waterturn-farmos-db",
    "--publish",
    "127.0.0.1:55432:5432",
    "--env-file",
    ".local/postgres.env",
    "--mount",
    "type=volume,source=waterturn-farmos-postgres,target=/var/lib/postgresql/data",
    "postgres:17-alpine@sha256:b0f9560a2de083e2cc7382e75f808c7381a32852a7ec49117deedb300e552b24",
  ]);
let ready = false;
for (let n = 0; n < 30; n++) {
  if (
    spawnSync(
      "docker",
      [
        "exec",
        "waterturn-farmos-db",
        "pg_isready",
        "-U",
        "postgres",
        "-d",
        "farmos",
      ],
      { stdio: "ignore" },
    ).status === 0
  ) {
    ready = true;
    break;
  }
  await new Promise((r) => setTimeout(r, 500));
}
if (!ready) throw Error("Database did not become ready.");
run("npx", ["tsx", "scripts/migrate.ts"]);
console.log(
  "Local PostgreSQL pilot prepared. Credentials remain in ignored local files; no users or default passwords were created.",
);
